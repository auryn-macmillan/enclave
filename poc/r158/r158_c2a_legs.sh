lines.append('\nCROSS-BASE (vs r152d c98b):')
lines.append(f'  A C2a: fold-base={A} vs r152d=1464743 (delta {A-1464743 if A else "?"})')
lines.append(f'  B family: A-B={A-B if A and B is not None else "?"} r152d-golden=552965 ')
lines.append(f'  C2b sanity: fold-base={E} vs r152d=2586563 (delta {E-2586563 if E else "?"})')
open(out+'/r158_delta.r158','w').write('\n'.join(lines)+'\n')
print('\n'.join(lines))
PY

echo "R158_STATUS=OK" | tee -a "$OUT/log.r158"
exit 0