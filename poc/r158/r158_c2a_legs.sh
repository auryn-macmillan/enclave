if A and B is not None and C is not None and B>=0 and C>=0:
  lines.append(f'\nC2a FAMILY = A-B = {A-B} g = {(A-B)/A*100 if A else 0:.2f}% of A leaf')
  lines.append(f'C2a PER-LIMB (spec-A) = A-C = {A-C} g = {(A-C)/A*100 if A else 0:.2f}% of A leaf; {(A-C)/(A-B)*100 if (A-B) else 0:.2f}% of family')
  lines.append(f'C2a FLAT (outside for-mod) = C-B = {C-B if C is not None else "?"} g')
