open(sys.argv[1]+"/r159_delta.r159","w").write(txt)
print(txt)
PY

# ============ STALE-ARTIFACT SENTINEL (pre-commit safety) ============
rm -f /tmp/r159/NEVER-SHIP-IF-THIS-ARTIFACT-IS-UNTRACKED
PORC_NONUNTRACKED=$(git -C /tmp/r159 status --porcelain | grep -v '^??' | wc -l)
log "PORC_NONUNTRACKED=$PORC_NONUNTRACKED"
[ "$PORC_NONUNTRACKED" -eq 0 ] || { log "LEG B left modified files"; exit 107; }
echo "R159_STATUS=OK" | tee -a "$OUT/log.r159"
exit 0