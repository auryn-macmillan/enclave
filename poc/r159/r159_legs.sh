  d=json.load(open(sys.argv[1]+"/"+t+"_gates.json"))
  return sum(f.get("circuit_size",0) for f in d.get("functions",[]))
A1=load("r159A1_live"); B=load("r159B_esm_lifted_solo")
# r157 goldens on the byte-identical locus (C1 leaf + family cells):
R157_A1=1634722; R157_B=620203; R157_C=823709
fam_r157=R157_A1-R157_B           # 1,014,519
limb_r157=R157_A1-R157_C          # 811,013
