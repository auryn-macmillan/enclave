    B  = {R157_B} g    (full range bullshit: eek+sk+e_sm_lifted+loop; r157 leg)
    C  = {R157_C} g    (per-limb loop only NOP; eek+sk+e_sm_lifted kept)
  base-stability check (A1 digits):  fold f7c87dbb9={A1}  vs c98b-r157=247298ad5:{R157_A1}
                                     delta {A1-R157_A1:+d}
