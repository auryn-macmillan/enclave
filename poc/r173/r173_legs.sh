lines=['ROUND=r173 BASE=f4ee7b7a8af1adf0006308b13c15d9ea04bd8411 (post-#2195-fold tip; OM 51f90114f; secure-50-coeffs shape)']
lines.append(f'LEG E1 (C2b unblunt, NEW shape)   = {E1}')
lines.append(f'LEG V4 (parity solo NOP, NEW)     = {V4}')
if E1 is not None and V4 is not None:
  cell=E1-V4
  lines.append(f'V4 CELL (new shape) = E1-V4 = {cell} g   vs OLD r164 cell 208896 g (delta {cell-208896}, ratio {cell/208896:.4f})')
  lines.append(f'E1 SHAPE SHIFT: new {E1} vs OLD golden 2586563 (delta {E1-2586563}, ratio {E1/2586563:.4f})')
  lines.append(f'V4 share of leaf: new {cell/E1*100:.2f}% vs OLD 8.08% (208896/2586563)')
open(out+'/r173_delta.r173','w').write('\n'.join(lines)+'\n')
print('\n'.join(lines))
