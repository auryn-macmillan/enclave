#!/usr/bin/env bash
# r173 - lane (i) V4-parity solo re-pin leg @ post-fold tip f4ee7b7a8 (OM 51f90114f).
# Owner armed 2026-10-18 ~13:35 EDT: "one solo-NOP + one unblunt leg at the
# current tip re-pinning the ~208,896 g parity cell (per r164/r170 numbering),
# completeness measurement for the cost table". The E1 unblunt leg doubles as
# the FIRST re-anchor datum at the new secure-50-coeffs shape (#2195 fold).
#
# 2-leg plan (sequential, taskset -c 0-3):
#   E1 : unblunt C2b at NEW base        -> OLD golden 2,586,563 g (delta = shape shift, EXPECTED nonzero now)
#   V4 : verify_parity_check solo NOP   -> OLD cell E1-V4 = 208,896 g (r164 @ cb722eea281)
# DERIVED: V4 cell (new shape) = E1 - V4. Same harness as r163/r164 (byte-proven).
set -u
export PATH="$HOME/.local/bin:$HOME/.nargo/bin:/usr/local/sbin:/usr/local/bin:/usr/sbin:/usr/bin:/sbin:/bin"
R=/tmp/r173
OUT=/home/dev/i5-rebase-wt/poc/r173
mkdir -p "$OUT"
BASE=f4ee7b7a8af1adf0006308b13c15d9ea04bd8411
BIN=$R/circuits/bin/dkg
# r173 FIX (upstream #2236 zk artifact-CLI refactor): nargo now emits bin artifacts to the
# WORKSPACE target dir circuits/bin/dkg/target/, not the per-package target/ r163/r170 used.
# First run's E1 compiled rc=0 wall 190s but the script's [ -s "$art" ] checked the old path -> E1_FAIL.
TGT=$BIN/target
[ "$(awk '/^MemAvailable:/{print $2}' /proc/meminfo)" -ge 12000000 ] || { echo [ERR] low-mem; exit 96; }
CIRB=e_sm_share_computation
log(){ echo "[$(date -u +%FT%TZ)] $*" | tee -a "$OUT/log.r173"; }
if [ -d "$R" ]; then
  HEAD_NOW=$(git -C "$R" rev-parse HEAD)
  if [ "$HEAD_NOW" = "$BASE" ]; then log "WORKTREE-EXISTING-REUSE @ $HEAD_NOW"; else log "WORKTREE-EXISTS-WRONG-SHA $HEAD_NOW"; exit 96; fi
else
  git -C /home/dev/interfold-research/interfold worktree add --detach "$R" "$BASE" >> "$OUT/log.r173" 2>&1 || { log WT_FAIL; exit 96; }
fi
cd "$R" || { log ERR; exit 98; }
[ "$(git rev-parse HEAD)" = "$BASE" ] || { log BASE-NOT-LOCKED; exit 97; }
log "HEAD=$(git rev-parse HEAD) CIRB=$CIRB"
DEF=$R/circuits/lib/src/configs/default/mod.nr
SC=$R/circuits/lib/src/core/dkg/share_computation.nr
# PRE shas pinned from disk at script authoring (post-fold tip f4ee7b7a8):
# DEF NEW sha 17c3347e... (upstream moved this file: insecure-64 preset + MAX_MSG=50);
# SC sha 44eb78d7... UNCHANGED vs r163/r164 pin (blob byte-flat across the fold, RAN r172).
PRE_DEF=17c3347ea8b3e1d5dbd7350bd3c1c1ade6dd349cdbfea60fc0fa87ee05841a02
PRE_SC=44eb78d704d0c4d63d0c50373c5be32242b5c1b93c0e93ae52bd60996ca29e48
[ "$(sha256sum "$DEF" | cut -d' ' -f1)" = "$PRE_DEF" ] || { log PRE_DEF_MISMATCH; exit 99; }
[ "$(sha256sum "$SC"  | cut -d' ' -f1)" = "$PRE_SC"  ] || { log PRE_SC_MISMATCH;  exit 99; }
cp -f "$DEF" "$OUT/zz_default_mod.nr.bak"
cp -f "$SC"  "$OUT/zz_share_computation.nr.bak"
restore(){
  cp -f "$OUT/zz_default_mod.nr.bak" "$DEF"
  cp -f "$OUT/zz_share_computation.nr.bak" "$SC"
  if [ "$(sha256sum "$DEF" | cut -d' ' -f1)" = "$PRE_DEF" ] && [ "$(sha256sum "$SC" | cut -d' ' -f1)" = "$PRE_SC" ]; then
    log "RESTORED rc=0"; return 0
  fi
  log "RESTORED rc=1 (sha mismatch!)"; return 1
}
trap 'log INTERRUPT-RESTORE; restore' TERM INT

flip_def(){
  python3 - "$DEF" <<'PY'
import sys
p=sys.argv[1]; a=open(p,encoding='utf-8').read()
# NOTE vs r163/r170: upstream #2226 moved the default preset insecure-512 -> insecure-64.
s=a.replace('Auto-generated by build-circuits.ts for preset: insecure-64',
            'Auto-generated by build-circuits.ts for preset: secure-8192')
s=s.replace('pub use super::insecure::dkg;','pub use super::secure::dkg;')
s=s.replace('pub use super::insecure::threshold;','pub use super::secure::threshold;')
assert s!=a, "preset flip miss"
open(p,'w').write(s); print("FLIP_OK")
PY
}
compile_one(){
  local tag=$1
  local art="$TGT/$CIRB.json"
  local s e rc
  cd "$R/circuits/bin/dkg/$CIRB" || { log "${tag}_CD_FAIL"; return 96; }
  rm -f "$art"
  s=$(date +%s)
  taskset -c 0-3 /usr/bin/time -v nargo compile --force > "$OUT/${tag}_stdout.log" 2> "$OUT/${tag}_timev.log"
  rc=$?
  e=$(date +%s)
  echo "$((e-s))s" > "$OUT/${tag}_wall.raw"
  log "$tag rc=$rc wall=$((e-s))s"
  cd "$R" || return 99
  [ $rc -ne 0 ] && return $rc
  [ -s "$art" ] || return 100
  cp -f "$art" "$OUT/${tag}_fresh.json"
  bb gates -b "$OUT/${tag}_fresh.json" -t noir-recursive-no-zk > "$OUT/${tag}_gates.json" 2> "$OUT/${tag}_gates_err.log"
  return 0
}
caption(){
  local tag=$1
  python3 - "$OUT" "$tag" <<'PY'
import json,sys,datetime
out,tag=sys.argv[1],sys.argv[2]
try:
  d=json.load(open(out+f'/{tag}_gates.json'))
  fns=d.get('functions',[]); g=sum(f.get('circuit_size',0) for f in fns); ac=sum(f.get('acir_opcodes',0) for f in fns)
  wall=0.0; peak=0
  for l in open(out+f'/{tag}_timev.log',errors='replace'):
    if 'Elapsed (wall clock)' in l:
      t=l.split(':',1)[1].strip().rsplit(' ',1)[-1]
      try: p=t.split(':'); wall=float(p[0])*60+float(p[1])
      except Exception: pass
    if 'Maximum resident set size' in l:
      peak=int(l.split()[-1])
  line=f"ROUND=r173 LEG={tag} BASE=f4ee7b7a8 DATE={datetime.datetime.utcnow().strftime('%Y-%m-%dT%H:%M:%SZ')} GATES={g} ACIR={ac} WALL={wall:.1f}s PEAK_KB={peak}"
except Exception as e:
  line=f'ROUND=r173 LEG={tag} PARSE_ERR={e}'
open(out+f'/{tag}.r173','w').write(line+"\n")
print(line)
PY
}
### ====== LEG E1: unblunt C2b @ new shape (first re-anchor datum; no LOC edit) ======
flip_def || { log FLIP_FAIL_E1; restore; echo "R173_STATUS=E1_FLIPFAIL" | tee -a "$OUT/log.r173"; exit 107; }
compile_one r173E1_c2b_unblunt || { log E1_FAIL; restore; echo "R173_STATUS=E1_FAIL" | tee -a "$OUT/log.r173"; exit 101; }
caption r173E1_c2b_unblunt || { log E1_PARSE_FAIL; restore; echo "R173_STATUS=E1_PARSE_FAIL" | tee -a "$OUT/log.r173"; exit 102; }
log "LEG_E1_DONE"
### ====== LEG V4: verify_parity_check solo NOP (r164-style whole-body comment-out) ======
python3 - "$SC" <<'PY'
import sys
p=sys.argv[1]; a=open(p,encoding='utf-8').read()
i=a.find('pub fn verify_parity_check')
assert i!=-1, 'fn header not found'
# r173 FIX: r164-style find(') {', i) hit the doc-comment call example
# "verify_parity_check::<...>(qis, h, y);" + newline + indented '{' (L106/L183 call sites),
# truncating the body-open BEFORE the real signature. Anchor on the multi-line signature's
# first param line, walk back to its '(', paren-match, then brace-match the body.
sig=a.find('\n    qis: [Field; L],', i)
assert sig!=-1, 'signature not found'
sig=a.rfind('(', i, sig)
assert sig!=-1, 'sig open paren not found'
# skip the signature parens (they contain '{' inside [Field; L] types) by bracket-matching ()
assert a[sig]=='('
pdepth=0; sigend=None
for j in range(sig, len(a)):
    c=a[j]
    if c=='(': pdepth+=1
    elif c==')':
        pdepth-=1
        if pdepth==0:
            sigend=j; break
assert sigend is not None, 'sig paren match failed'
op=a.find('{', sigend)
assert op!=-1
depth=0; cl=None
for j in range(op, len(a)):
    c=a[j]
    if c=='{': depth+=1
    elif c=='}':
        depth-=1
        if depth==0:
            cl=j+1; break
assert cl is not None, 'brace match failed'
body=a[op+1:cl-1]
V='\n'.join(('    // V4-NOP '+ln if ln.strip() else ln) for ln in body.split('\n'))
s2=a[:op+1]+V+a[cl-1:]
assert s2.count('V4-NOP')>=1
assert s2.count('{')==a.count('{') and s2.count('}')==a.count('}'), 'brace balance broken'
# sanity: the next fn header must NOT be commented out
assert '\n// V4-NOP ///' not in s2 and '\n// V4-NOP pub fn' not in s2, 'splice bled past fn end'
open(p,'w').write(s2); print('NOP_V4_OK whole_verify_parity_check_body')
PY
[ $? -eq 0 ] || { log SPFAIL_V4; restore; echo "R173_STATUS=SPFAIL_V4" | tee -a "$OUT/log.r173"; exit 104; }
[ "$(sha256sum "$SC" | cut -d' ' -f1)" != "$PRE_SC" ] || { log V4_NOCHANGE; restore; echo "R173_STATUS=V4_NOCHANGE" | tee -a "$OUT/log.r173"; exit 105; }
compile_one r173V4_c2b_parity_solo || { log V4_FAIL; restore; echo "R173_STATUS=V4_FAIL" | tee -a "$OUT/log.r173"; exit 103; }
caption r173V4_c2b_parity_solo || { log V4_PARSE_FAIL; restore; echo "R173_STATUS=V4_PARSE_FAIL" | tee -a "$OUT/log.r173"; exit 106; }
log "LEG_V4_DONE"
restore
R_RESTORE=$?
log "RESTORE rc=$R_RESTORE after leg V4"
git -C "$R" status --porcelain | grep -v '^??' | head -5
python3 - "$OUT" <<'PY'
